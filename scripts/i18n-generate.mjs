import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const directory = path.join(root, 'src/localization/locales');
const files = fs.readdirSync(directory).filter(name => name.endsWith('.json')).sort();
const codes = new Set();
const imports = [], entries = [];
for (const [i, file] of files.entries()) {
  const { meta, messages } = JSON.parse(fs.readFileSync(path.join(directory, file), 'utf8'));
  if (!meta || meta.code !== file.slice(0, -5) || !/^[a-z]{2,3}(?:-[A-Za-z0-9]+)*$/.test(meta.code) || codes.has(meta.code)) throw Error(`Invalid locale metadata: ${file}`);
  if (!meta.name || !meta.nativeName || !['ltr', 'rtl'].includes(meta.direction) || !meta.fallback || !messages || Object.values(messages).some(value => typeof value !== 'string')) throw Error(`Invalid language pack: ${file}`);
  codes.add(meta.code);
  imports.push(`import pack${i} from './locales/${file}';`);
  entries.push(`  ${JSON.stringify(meta.code)}: pack${i} as LanguagePack,`);
}
if (!codes.has('en') || !codes.has('zh')) throw Error('English and Chinese source language packs are required');
const generated = `// Generated by scripts/i18n-generate.mjs. Add/edit locale JSON files; do not edit this registry.\nimport type { LanguagePack } from './types.js';\n${imports.join('\n')}\nexport const languagePacks: Record<string, LanguagePack> = {\n${entries.join('\n')}\n};\n`;
const target = path.join(root, 'src/localization/registry.generated.ts');
if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== generated) fs.writeFileSync(target, generated);
console.log(`Language registry: ${files.length} packs`);
